/**
 * 把卡片按段时长排成 [t, d]，关键词自动穿进 z。
 * 卡片等权；可用 w 覆盖。空档用 {gap: true} 表示。
 */
export function scheduleCards(cards, seconds) {
  const weights = cards.map((card) => (card && Number.isFinite(card.w) ? card.w : 1))
  const total = weights.reduce((sum, value) => sum + value, 0)
  let cursor = 0
  const out = []
  for (let index = 0; index < cards.length; index += 1) {
    const card = cards[index]
    const duration = (seconds * weights[index]) / total
    out.push({ t: Math.round(cursor * 100) / 100, d: Math.round(duration * 100) / 100, text: card.text, z: card.z ?? [] })
    cursor += duration
  }
  return out
}

